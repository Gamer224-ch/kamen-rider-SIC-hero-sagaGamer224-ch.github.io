/* ---------- Estado y utilidades ---------- */

const DEFAULT_LANG = "es";
const STORAGE_LANG = "kr-sic-lang";

function getLang() {
  let saved = null;
  try { saved = localStorage.getItem(STORAGE_LANG); } catch (e) { /* ignore */ }
  if (saved === "es" || saved === "en") return saved;
  return DEFAULT_LANG;
}

function t(key) {
  const lang = getLang();
  return (I18N[lang] && I18N[lang][key]) || I18N.es[key] || key;
}

/* Aplica el idioma a los elementos estáticos marcados con data-i18n */
function applyLang(lang) {
  lang = lang || getLang();
  document.documentElement.lang = lang === "es" ? "es" : "en";

  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    const key = el.getAttribute("data-i18n");
    const val = (I18N[lang] && I18N[lang][key]) || I18N.es[key] || key;
    if (val) el.textContent = val;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-placeholder");
    const val = (I18N[lang] && I18N[lang][key]) || I18N.es[key] || key;
    if (val) el.placeholder = val;
  });

  document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-aria");
    const val = (I18N[lang] && I18N[lang][key]) || I18N.es[key] || key;
    if (val) el.setAttribute("aria-label", val);
  });

  document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-title");
    const val = (I18N[lang] && I18N[lang][key]) || I18N.es[key] || key;
    if (val) el.setAttribute("title", val);
  });

  // Notificar a app.js para re-renderizar contenido dinámico
  document.dispatchEvent(new CustomEvent("kr:langchange", { detail: { lang: lang } }));
}

function setLang(lang) {
  try { localStorage.setItem(STORAGE_LANG, lang); } catch (e) { /* ignore */ }
  applyLang(lang);
  updateLangButtons(lang);
}

function updateLangButtons(lang) {
  document.querySelectorAll("[data-lang-btn]").forEach(function (btn) {
    const target = btn.getAttribute("data-lang-btn");
    const isActive = target === lang;
    btn.setAttribute("aria-pressed", isActive ? "true" : "false");
    btn.classList.toggle("is-active", isActive);
  });
  document.querySelectorAll("[data-lang-current]").forEach(function (el) {
    el.textContent = (lang || getLang()).toUpperCase();
  });
}
